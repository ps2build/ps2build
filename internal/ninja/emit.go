package ninja

import (
	"io"
	"strings"

	"github.com/ps2build/ps2build/internal/buildgraph"
)

var (
	eeGCC     = "mips64r5900el-ps2-elf-gcc"
	eeGXX     = "mips64r5900el-ps2-elf-g++"
	eeObjcopy = "mips64r5900el-ps2-elf-objcopy"
	eeAR      = "mips64r5900el-ps2-elf-ar"
	eeStrip   = "mips64r5900el-ps2-elf-strip"

	iopGCC   = "mipsel-none-elf-gcc"
	iopStrip = "mipsel-none-elf-strip"
	iopAR    = "mipsel-none-elf-ar"

	dvpAS   = "dvp-as"
	vclTool = "vcl"
)

// Emit writes a complete build.ninja for g to w.
func Emit(g *buildgraph.Graph, w io.Writer) error {
	nw := NewWriter(w)

	nw.Comment("Generated by ps2build. Do not edit by hand.")
	nw.Blank()

	usage := computeRspUsage(g)
	writeRules(nw, g, usage)
	nw.Blank()

	for _, ie := range g.IETableStubs {
		writeIETableStubEdge(nw, ie)
	}
	for _, c := range g.Compiles {
		writeCompileEdge(nw, c)
	}
	for _, a := range g.Archives {
		writeArchiveEdge(nw, a)
	}
	for _, l := range g.Links {
		writeLinkEdge(nw, l, g.Toolchain.EELinkTrailer() != "")
	}
	for _, s := range g.Strips {
		writeStripEdge(nw, s)
	}
	for _, f := range g.Fixups {
		writeFixupEdge(nw, f)
	}
	for _, b := range g.Bin2Cs {
		writeBin2CEdge(nw, b)
	}
	for _, o := range g.Objcopies {
		writeObjcopyEdge(nw, o)
	}
	for _, p := range g.Packs {
		writePackEdge(nw, p)
	}

	nw.Blank()
	for _, name := range g.TargetOrder {
		out, ok := g.TargetOutputs[name]
		if !ok {
			continue
		}
		nw.Phony(name, []string{out})
	}

	nw.Blank()
	allOutputs := make([]string, 0, len(g.TargetOrder))
	for _, name := range g.TargetOrder {
		if _, ok := g.TargetOutputs[name]; ok {
			allOutputs = append(allOutputs, name)
		}
	}
	nw.Phony("all", allOutputs)
	nw.Default([]string{"all"})

	return nw.Err()
}

func tool(toolchains map[string]string, name string) string {
	if resolved, ok := toolchains[name]; ok {
		return resolved
	}
	return name
}

const cmdLengthThreshold = 6000

func tooLong(parts ...[]string) bool {
	total := 0
	for _, p := range parts {
		for _, s := range p {
			total += len(s) + 1
		}
	}
	return total > cmdLengthThreshold
}

type rspUsage struct {
	eeCC, eeCXX, iopCC         bool
	eeLink, eeLinkCXX, iopLink bool
}

func computeRspUsage(g *buildgraph.Graph) rspUsage {
	var u rspUsage
	for _, c := range g.Compiles {
		if !tooLong(c.FlagArgs) {
			continue
		}
		switch c.Toolchain {
		case eeGCC:
			u.eeCC = true
		case eeGXX:
			u.eeCXX = true
		case iopGCC:
			u.iopCC = true
		}
	}
	for _, l := range g.Links {
		if !linkTooLong(l) {
			continue
		}
		switch l.Toolchain {
		case iopGCC:
			u.iopLink = true
		case eeGXX:
			u.eeLinkCXX = true
		default:
			u.eeLink = true
		}
	}
	return u
}

func linkTooLong(l buildgraph.LinkStep) bool {
	flags := append(dirFlags(l.LocalLibDirs), l.FlagArgs...)
	return tooLong(l.Objects, flags, libFlags(l.Libs))
}

func writeRules(nw *Writer, g *buildgraph.Graph, usage rspUsage) {
	toolchains := g.ToolchainPaths
	tc := g.Toolchain

	nw.RuleCompile("ee_cc", tool(toolchains, eeGCC)+" -MMD -MF $out.d $flags -c $in -o $out", "CC(ee) $out")
	nw.RuleCompile("ee_cxx", tool(toolchains, eeGXX)+" -MMD -MF $out.d $flags -c $in -o $out", "CXX(ee) $out")
	nw.RuleCompile("iop_cc", tool(toolchains, iopGCC)+" -MMD -MF $out.d $flags -c $in -o $out", "CC(iop) $out")
	if usage.eeCC {
		nw.RuleCompileWithRspfile("ee_cc_rsp", tool(toolchains, eeGCC)+" -MMD -MF $out.d @$out.rsp -c $in -o $out", "$out.rsp", "$flags", "CC(ee) $out")
	}
	if usage.eeCXX {
		nw.RuleCompileWithRspfile("ee_cxx_rsp", tool(toolchains, eeGXX)+" -MMD -MF $out.d @$out.rsp -c $in -o $out", "$out.rsp", "$flags", "CXX(ee) $out")
	}
	if usage.iopCC {
		nw.RuleCompileWithRspfile("iop_cc_rsp", tool(toolchains, iopGCC)+" -MMD -MF $out.d @$out.rsp -c $in -o $out", "$out.rsp", "$flags", "CC(iop) $out")
	}
	for _, c := range g.Compiles {
		if c.VCL {
			nw.RuleCompile("vcl", tool(toolchains, vclTool)+" -c -MD -MF $out.d $flags $in -o $out", "VCL $out")
			break
		}
	}
	nw.Rule("dvp_as", tool(toolchains, dvpAS)+" $in -o $out $flags", "DVPAS $out")

	eeLinkTool, eeLinkToolCXX, iopLinkTool := tc.EELinkTool(false), tc.EELinkTool(true), tc.IOPLinkTool()
	eeTrailer := tc.EELinkTrailer()
	if eeTrailer != "" {
		nw.Variable("deflibs", strings.TrimSpace(eeTrailer))
		eeTrailer = " $deflibs"
	}

	// $in must precede $flags/$libs: a single-pass linker won't resolve symbols from a lib that appears before the object referencing it.
	nw.Rule("ee_link", tool(toolchains, eeLinkTool)+" -T$linkfile -o $out $in $flags $libs"+eeTrailer, "LINK(ee) $out")
	nw.Rule("ee_link_cxx", tool(toolchains, eeLinkToolCXX)+" -T$linkfile -o $out $in $flags $libs"+eeTrailer, "LINK(ee,c++) $out")
	nw.Rule("iop_link", tool(toolchains, iopLinkTool)+" -T$linkfile -o $out $in $flags $libs", "LINK(iop) $out")
	if usage.eeLink {
		nw.RuleWithRspfile("ee_link_rsp", tool(toolchains, eeLinkTool)+" -T$linkfile -o $out @$out.rsp"+eeTrailer, "$out.rsp", "$in $flags $libs", "LINK(ee) $out")
	}
	if usage.eeLinkCXX {
		nw.RuleWithRspfile("ee_link_cxx_rsp", tool(toolchains, eeLinkToolCXX)+" -T$linkfile -o $out @$out.rsp"+eeTrailer, "$out.rsp", "$in $flags $libs", "LINK(ee,c++) $out")
	}
	if usage.iopLink {
		nw.RuleWithRspfile("iop_link_rsp", tool(toolchains, iopLinkTool)+" -T$linkfile -o $out @$out.rsp", "$out.rsp", "$in $flags $libs", "LINK(iop) $out")
	}

	nw.Rule("ee_strip", tool(toolchains, eeStrip)+" $flags -o $out $in", "STRIP $out")
	nw.Rule("iop_strip", tool(toolchains, iopStrip)+" $flags -o $out $in", "STRIP $out")
	nw.Rule("iop_fixup", tool(toolchains, "iopfixup")+" $flags -o $out $in", "IOPFIXUP $out")
	nw.Rule("bin2c", tool(toolchains, "bin2c")+" $in $out $varname", "BIN2C $out")
	nw.Rule("ee_objcopy", tool(toolchains, eeObjcopy)+" -O binary $in $out", "OBJCOPY $out")
	nw.Rule("ee_pack", tool(toolchains, "ps2pack")+" $in $out", "PS2PACK $out")

	nw.Rule("ee_ar", tool(toolchains, eeAR)+" rcs $out $in", "AR(ee) $out")
	nw.Rule("iop_ar", tool(toolchains, iopAR)+" rcs $out $in", "AR(iop) $out")

	if len(g.IETableStubs) > 0 {
		nw.Rule("iop_ietable_stub", tool(toolchains, "ps2build")+" genirx-stub --header $header --in $in --out $out", "GENIRX $out")
	}
}

func compileRuleFor(toolchain string) string {
	switch toolchain {
	case eeGCC:
		return "ee_cc"
	case eeGXX:
		return "ee_cxx"
	case iopGCC:
		return "iop_cc"
	case dvpAS:
		return "dvp_as"
	case vclTool:
		return "vcl"
	default:
		return "ee_cc"
	}
}

func writeCompileEdge(nw *Writer, c buildgraph.CompileStep) {
	rule := compileRuleFor(c.Toolchain)
	if !c.Assembler && !c.VCL && tooLong(c.FlagArgs) {
		rule += "_rsp"
	}
	nw.Build(BuildEdge{
		Outputs: []string{c.Object},
		Rule:    rule,
		Inputs:  []string{c.Source},
		Vars:    [][2]string{{"flags", strings.Join(c.FlagArgs, " ")}},
	})
}

func writeLinkEdge(nw *Writer, l buildgraph.LinkStep, hasDefaultLibs bool) {
	rule := "ee_link"
	switch l.Toolchain {
	case iopGCC:
		rule = "iop_link"
	case eeGXX:
		rule = "ee_link_cxx"
	}
	flags := append(dirFlags(l.LocalLibDirs), l.FlagArgs...)
	if linkTooLong(l) {
		rule += "_rsp"
	}
	vars := [][2]string{
		{"linkfile", l.Linkfile},
		{"flags", strings.Join(flags, " ")},
		{"libs", strings.Join(libFlags(l.Libs), " ")},
	}
	if hasDefaultLibs && l.NoDefaultLibs && l.Toolchain != iopGCC {
		vars = append(vars, [2]string{"deflibs", ""})
	}
	nw.Build(BuildEdge{
		Outputs:  []string{l.Output},
		Rule:     rule,
		Inputs:   l.Objects,
		Vars:     vars,
		Implicit: append(append([]string{l.Linkfile}, l.LibDeps...), l.ExternalLibDeps...),
	})
}

func writeStripEdge(nw *Writer, s buildgraph.StripStep) {
	rule := "iop_strip"
	if s.Toolchain == eeStrip {
		rule = "ee_strip"
	}
	nw.Build(BuildEdge{
		Outputs: []string{s.Output},
		Rule:    rule,
		Inputs:  []string{s.Input},
		Vars:    [][2]string{{"flags", strings.Join(s.FlagArgs, " ")}},
	})
}

func writeFixupEdge(nw *Writer, f buildgraph.FixupStep) {
	nw.Build(BuildEdge{
		Outputs: []string{f.Output},
		Rule:    "iop_fixup",
		Inputs:  []string{f.Input},
		Vars:    [][2]string{{"flags", strings.Join(f.FlagArgs, " ")}},
	})
}

func writeBin2CEdge(nw *Writer, b buildgraph.Bin2CStep) {
	nw.Build(BuildEdge{
		Outputs: []string{b.COutPath.String()},
		Rule:    "bin2c",
		Inputs:  []string{b.IRXPath},
		Vars:    [][2]string{{"varname", b.VarName}},
	})
}

func writeIETableStubEdge(nw *Writer, ie buildgraph.IETableStubStep) {
	nw.Build(BuildEdge{
		Outputs: []string{ie.COutPath.String()},
		Rule:    "iop_ietable_stub",
		Inputs:  []string{ie.SourceFile},
		Vars:    [][2]string{{"header", ie.Header}},
	})
}

func writeArchiveEdge(nw *Writer, a buildgraph.ArchiveStep) {
	rule := "ee_ar"
	if a.Toolchain == iopAR {
		rule = "iop_ar"
	}
	nw.Build(BuildEdge{
		Outputs: []string{a.Output},
		Rule:    rule,
		Inputs:  a.Objects,
	})
}

func writeObjcopyEdge(nw *Writer, o buildgraph.ObjcopyStep) {
	nw.Build(BuildEdge{
		Outputs: []string{o.Output},
		Rule:    "ee_objcopy",
		Inputs:  []string{o.Input},
	})
}

func writePackEdge(nw *Writer, p buildgraph.PackStep) {
	nw.Build(BuildEdge{
		Outputs: []string{p.Output},
		Rule:    "ee_pack",
		Inputs:  []string{p.Input},
	})
}

func libFlags(libs []string) []string {
	out := make([]string, len(libs))
	for i, l := range libs {
		out[i] = "-l" + l
	}
	return out
}

func dirFlags(dirs []string) []string {
	out := make([]string, len(dirs))
	for i, d := range dirs {
		out[i] = "-L" + d
	}
	return out
}
